#!/usr/bin/env python3
"""Converts ui/index.html into RPI/ui_html.h (a C string constant)."""
import sys

src, dst = sys.argv[1], sys.argv[2]
data = open(src, 'rb').read().replace(b'\r\n', b'\n')

out = ['/* Generated by tools/gen_ui_header.py. Do not edit. */',
       '#ifndef UI_HTML_H', '#define UI_HTML_H', '',
       'static const char g_ui_html[] =']
lines = data.split(b'\n')
if lines and lines[-1] == b'':
    lines.pop()
for raw in lines:
    esc = ''
    for b in raw:
        c = chr(b)
        if c == '\\':
            esc += '\\\\'
        elif c == '"':
            esc += '\\"'
        elif c == '?':
            esc += '\\?'          # avoid trigraphs
        elif 32 <= b < 127:
            esc += c
        elif c == '\t':
            esc += '\\t'
        else:
            esc += '\\%03o' % b   # UTF-8 bytes as octal escapes
    out.append('\t"' + esc + '\\n"')
out[-1] += ';'
out += ['', '#endif', '']
open(dst, 'w', newline='\n').write('\n'.join(out))
print('wrote', dst, len(data), 'bytes of HTML')
